"""Database tables.

Rules followed by every table:
- UUID primary keys, generated by the application.
- Timestamps are timezone-aware (UTC).
- No passwords and no raw JWTs are ever stored. Passwords will belong to the
  identity provider; the Marketplace JWT is verified and then discarded.
- The temporary Marketplace ``state`` is stored only as a SHA-256 hash.

Any change here needs a new Alembic migration (see README.md).
"""
import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    MetaData,
    String,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

# Fixed constraint names, so migrations are predictable and easy to read.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

ORGANISATION_ROLES = ("owner", "admin", "member")
APPROVAL_STATUSES = ("pending", "approved", "rejected")


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(Uuid, primary_key=True, default=uuid.uuid4)


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


def _updated_at() -> Mapped[datetime]:
    return mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )


def _in_list(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


class User(Base):
    """A person who signs in. Created when authentication is added (not yet)."""

    __tablename__ = "users"

    id: Mapped[uuid.UUID] = _uuid_pk()
    # The identity provider's stable user ID (the token's "sub" claim).
    idp_subject: Mapped[str] = mapped_column(String(255), nullable=False, unique=True)
    email: Mapped[str] = mapped_column(String(320), nullable=False, index=True)
    display_name: Mapped[str | None] = mapped_column(String(200))
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()

    memberships: Mapped[list["OrganisationMember"]] = relationship(back_populates="user")


class Organisation(Base):
    """A customer company. Marketplace accounts are linked to organisations, not users."""

    __tablename__ = "organisations"

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()

    members: Mapped[list["OrganisationMember"]] = relationship(
        back_populates="organisation", cascade="all, delete-orphan", passive_deletes=True
    )


class OrganisationMember(Base):
    """Which users belong to which organisation, and with what role."""

    __tablename__ = "organisation_members"
    __table_args__ = (
        UniqueConstraint("organisation_id", "user_id"),
        CheckConstraint(_in_list("role", ORGANISATION_ROLES), name="role"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    organisation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organisations.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    role: Mapped[str] = mapped_column(String(20), nullable=False, default="member")
    created_at: Mapped[datetime] = _created_at()

    organisation: Mapped[Organisation] = relationship(back_populates="members")
    user: Mapped[User] = relationship(back_populates="memberships")


class MarketplaceSignupSession(Base):
    """A verified Marketplace sign-up, waiting for the customer to register.

    Created from Google's JWT on POST /marketplace/signup. The browser only
    holds the raw ``state``; this table holds its SHA-256 hash.
    """

    __tablename__ = "marketplace_signup_sessions"
    __table_args__ = (
        CheckConstraint("char_length(state_hash) = 64", name="state_hash_length"),
        CheckConstraint("expires_at > created_at", name="expires_after_created"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    # Hex SHA-256 of the state. Never the state itself.
    state_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    # JWT "sub". Never sent to the browser.
    procurement_account_id: Mapped[str] = mapped_column(String(255), nullable=False, index=True)
    # JWT google.user_identity. Never sent to the browser.
    user_identity: Mapped[str | None] = mapped_column(String(255))
    # JWT google.roles, e.g. ["account_admin"]
    roles: Mapped[list[str]] = mapped_column(JSONB, nullable=False, default=list)
    # JWT google.orders, or None unless multiple orders are enabled
    orders: Mapped[list[str] | None] = mapped_column(JSONB)
    created_at: Mapped[datetime] = _created_at()
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    # Set when a signed-in user takes over this sign-up (a later milestone).
    claimed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    claimed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class MarketplaceAccountLink(Base):
    """Which organisation owns a Google Procurement account. One owner per account."""

    __tablename__ = "marketplace_account_links"
    __table_args__ = (
        CheckConstraint(_in_list("approval_status", APPROVAL_STATUSES), name="approval_status"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    procurement_account_id: Mapped[str] = mapped_column(String(255), nullable=False, unique=True)
    # RESTRICT: an organisation cannot be deleted while it owns a Marketplace account.
    organisation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organisations.id", ondelete="RESTRICT"), nullable=False, index=True
    )
    signup_session_id: Mapped[uuid.UUID | None] = mapped_column(
        # Named explicitly: the generated name would exceed PostgreSQL's 63-character limit.
        ForeignKey(
            "marketplace_signup_sessions.id",
            ondelete="SET NULL",
            name="fk_marketplace_account_links_signup_session_id",
        )
    )
    linked_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    # Record only: nothing calls the Procurement API in this milestone.
    approval_status: Mapped[str] = mapped_column(String(20), nullable=False, default="pending")
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()

    organisation: Mapped[Organisation] = relationship()
